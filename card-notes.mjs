export function imageNote(card) {
  if (card.arcana === 'major') return major[card.rank];
  const [scene, tension, practice] = suitScenes[card.suit];
  const [rankScene, rankPractice] = rankScenes[card.rank - 1];
  return [`${scene}；${rankScene}`, `${tension}，而这张牌还提醒人留意阶段中的取舍`, `${practice}，再${rankPractice}`];
}
